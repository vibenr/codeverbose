import os
import subprocess

import pytest

from codeverbose import labeling
from codeverbose.labeling import AI, HUMAN, MIXED, UNLABELED, CommitInfo, Labeler, function_label


def _commit(message="", author="Dev <dev@example.com>", ts=1_800_000_000):
    return CommitInfo(sha="a" * 40, author=author, timestamp=ts, message=message)


@pytest.mark.parametrize(
    "message",
    [
        "feat: x\n\nCo-Authored-By: Claude <noreply@anthropic.com>",
        "fix\n\nCo-authored-by: Copilot <175728472+Copilot@users.noreply.github.com>",
        "x\n\n\U0001f916 Generated with [Claude Code](https://claude.com/claude-code)",
        "aider: refactor parser",
        "y\n\nGenerated by Cursor",
    ],
)
def test_ai_messages(message):
    assert Labeler(repo=".").classify(_commit(message))[0] == AI


def test_human_trailer_not_ai():
    msg = "feat\n\nCo-authored-by: Cody Smith <cody@example.com>"
    assert Labeler(repo=".").classify(_commit(msg))[0] == UNLABELED


def test_before_cutoff_is_human_and_assume_human():
    assert Labeler(repo=".").classify(_commit(ts=1_500_000_000))[0] == HUMAN
    assert Labeler(repo=".", assume_human=True).classify(_commit())[0] == HUMAN


def test_rules_file(tmp_path):
    rules = tmp_path / "labels.csv"
    rules.write_text("kind,pattern,label\n# comment\nauthor,bot@corp,ai\npath,legacy/**,human\n")
    lab = Labeler(repo=".", rules=labeling.load_rules(rules))
    assert lab.classify(_commit(author="Build <bot@corp.com>"))[0] == AI
    assert lab.path_override("legacy/a/b.py") == HUMAN
    assert lab.path_override("src/b.py") is None


def test_function_label_majority_and_mixed():
    lines = {1: AI, 2: AI, 3: AI, 4: HUMAN}
    assert function_label(lines, 1, 4, 0.6) == (AI, 0.75)
    assert function_label({1: AI, 2: HUMAN}, 1, 2, 0.6)[0] == MIXED
    assert function_label({}, 1, 2, 0.6)[0] == UNLABELED


def _git(cwd, *args, env=None):
    subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True, env=env)


@pytest.fixture
def repo(tmp_path):
    _git(tmp_path, "init", "-q")
    _git(tmp_path, "config", "user.email", "dev@example.com")
    _git(tmp_path, "config", "user.name", "Dev")
    old = dict(
        os.environ, GIT_AUTHOR_DATE="2020-01-01T00:00:00", GIT_COMMITTER_DATE="2020-01-01T00:00:00"
    )
    (tmp_path / "old.py").write_text("def f(x):\n    y = x + 1\n    return y\n")
    _git(tmp_path, "add", ".", env=old)
    _git(tmp_path, "commit", "-qm", "old", env=old)
    (tmp_path / "new.py").write_text(
        "def g(values):\n    # Initialize the result\n    result = []\n"
        "    for value in values:\n        result.append(value)\n    return result\n"
    )
    _git(tmp_path, "add", ".")
    _git(tmp_path, "commit", "-qm", "new\n\nCo-Authored-By: Claude <noreply@anthropic.com>")
    return tmp_path


def test_blame_labels(repo):
    lab = Labeler(repo=repo)
    lab.load_history()
    assert lab.blame_labels("old.py") == {1: HUMAN, 2: HUMAN, 3: HUMAN}
    assert set(lab.blame_labels("new.py").values()) == {AI}
